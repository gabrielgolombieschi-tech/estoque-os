import fs from "node:fs";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { tenantId,empresaId,diretorio,validarEscopo,impressaoTecnica } from "./lib/controle-revisoes.mjs";
import { ids009,grupos009,validarCinquenta,assinatura } from "./lib/lotes-cinquenta.mjs";
import { normalizarNomeCadastro } from "../lib/itens/normalizacaoNome.ts";

// Preparação local: não conecta ao ERP e não concede aprovação.
const arquivoBase = "backups/base-revisao/2026-09-09T21-16-35-648Z.json";
const base = JSON.parse(fs.readFileSync(arquivoBase,"utf8"));
validarEscopo(base);
const rascunhos = JSON.parse(fs.readFileSync("scripts/descricoes-lote-009.json","utf8"));
const fontes = JSON.parse(fs.readFileSync("scripts/fontes-lote-009.json","utf8"));
assert.equal(rascunhos.length,50);
assert.equal(new Set(rascunhos.map(i=>i.id)).size,50);
const eventos = fs.readdirSync(diretorio).filter(f=>/^eventos-.*\.json$/.test(f)).flatMap(f=>JSON.parse(fs.readFileSync(`${diretorio}/${f}`,"utf8")));
eventos.forEach(validarEscopo);
const itens = ids009.map(id=>{
  const antes = base.itens.find(i=>i.id===id);
  const d = rascunhos.find(i=>i.id===id);
  const f = fontes.find(i=>i.id===id);
  assert.ok(antes && d && f); validarEscopo(antes);
  assert.ok(!eventos.some(e=>e.item_id===id),`Já revisado: ${id}`);
  assert.equal(antes.codigo_interno,f.c);
  const chave = f.arquivo ?? String(id);
  const pasta = "backups/fontes-lote-009";
  const texto = fs.readFileSync(`${pasta}/${chave}.txt`,"utf8");
  const referencia = d.referencia ?? f.url.match(/dataSheet_(.+)_\d+_[a-z]{2}\.pdf/)?.[1];
  assert.ok(referencia && texto.includes(f.c),`Código na fonte: ${id}`);
  assert.ok(texto.replace(/\s/g,"").toUpperCase().includes(referencia.toUpperCase()),`Modelo na fonte: ${id}`);
  const paginas = d.paginas ?? [2,3];
  for (const p of paginas) assert.ok(fs.existsSync(`${pasta}/${chave}-p${p}.png`));
  const arquivo = `${pasta}/${chave}.pdf`;
  const fonte = JSON.parse(fs.readFileSync(`${pasta}/${chave}.fonte.json`,"utf8"));
  assert.equal(fonte.url,f.url);
  const evidencia = {arquivo,documento:f.tipo_fonte ?? `Ficha SICK ${referencia}`,paginas,sha256:createHash("sha256").update(fs.readFileSync(arquivo)).digest("hex"),url:fonte.url,consultado_em:fonte.consultado_em};
  const familia = Object.entries(grupos009).find(([,g])=>g===antes.grupo_id)?.[0];
  assert.ok(familia);
  const nome = normalizarNomeCadastro(d.nome);
  const descricao_tecnica = `Referência SICK ${referencia}. ${d.desc} Especificação da referência consultada; conferir versão física e condições de aplicação. O cadastro não certifica a segurança da instalação.`;
  const descricao = [`Cadastro anterior preservado como histórico (não validado integralmente):\n${antes.nome}${antes.descricao ? `\n${antes.descricao}` : ""}`,descricao_tecnica,`Fontes técnicas consultadas em 2026-09-09:\n${fonte.url}`].join("\n\n");
  return {id,antes,impressao_antes:impressaoTecnica(antes),familia,criterio:`${familia}:proposta009`,referencia,nome,descricao_tecnica,depois:{nome,descricao},fontes:[fonte.url],evidencia,pendencias:[],atributos_nao_confirmados:d.nao_confirmados??[]};
});
const m = {tenant_id:tenantId,empresa_id:empresaId,numero:"009",lote:"009-cinquenta-itens",data:"2026-09-09",responsavel:"Revisão assistida Codex; proposta sujeita à aprovação humana",autorizacao:"aguardando_aprovacao_humana",base:arquivoBase,itens};
validarCinquenta(m);
const destino = `${diretorio}/lote-${m.lote}.json`;
if (fs.existsSync(destino)) assert.deepEqual(JSON.parse(fs.readFileSync(destino,"utf8")),m,"Não sobrescrever proposta congelada");
else fs.writeFileSync(destino,JSON.stringify(m,null,2),{flag:"wx"});
console.log(JSON.stringify({lote:m.lote,itens:50,assinatura:assinatura(m),aplicados:0}));
