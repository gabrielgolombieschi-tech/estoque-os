import assert from "node:assert/strict";
import fs from "node:fs";
import yaml from "js-yaml";
import { tenantId, empresaId, impressaoTecnica, situacaoRevisao, validarLote } from "./lib/controle-revisoes.mjs";
import { montarPlano } from "./lib/plano-revisao-fabricantes.mjs";
const item = { id: 1, codigo_interno: "ABC", nome: "CONTATOR", descricao: null, unidade_medida: "UN", fator_conversao: 1 };
const evento = { tenant_id: tenantId, empresa_id: empresaId, item_id: 1, familia: "CONTATORES", criterio: "CONTATORES:1", revisado_em: "2026-09-05T12:00:00Z", status: "aprovado", impressao_tecnica: impressaoTecnica(item) };
assert.equal(situacaoRevisao(item, []), "nao_revisado");
assert.equal(situacaoRevisao(item, [], [{ id: 1 }]), "historico_recuperado");
const informado = [{ id: 1, codigo: "ABC" }];
assert.equal(situacaoRevisao(item, [], [], informado), "historico_informado");
assert.equal(situacaoRevisao(item, [], [{ id: 1 }], informado), "historico_recuperado");
assert.equal(situacaoRevisao(item, [evento], [], informado), "aprovado");
assert.equal(situacaoRevisao({ ...item, codigo_interno: "OUTRO" }, [], [], informado), "nao_revisado");
assert.equal(situacaoRevisao({ ...item, id: 2, grupo_id: 17 }, [], [], informado), "nao_revisado");
assert.equal(situacaoRevisao(item, [evento], [{ id: 1 }]), "aprovado");
assert.equal(situacaoRevisao({ ...item, preco: 10, saldo: 20, atualizado_em: "outro", ativo: false }, [evento]), "aprovado");
for (const campo of ["nome", "descricao", "codigo_interno", "unidade_medida", "fator_conversao", "grupo_id", "fabricante", "fornecedor_id"]) {
  assert.equal(situacaoRevisao({ ...item, [campo]: "mudou" }, [evento]), "reavaliar", campo);
}
assert.equal(situacaoRevisao(item, [{ ...evento, criterio: "CONTATORES:0" }]), "reavaliar");
assert.equal(situacaoRevisao(item, [{ ...evento, status: "pendente" }]), "pendente");
assert.throws(() => situacaoRevisao(item, [{ ...evento, empresa_id: "outra" }]));
assert.throws(() => situacaoRevisao(item, [{ ...evento, tenant_id: "outro" }]));
const m = JSON.parse(fs.readFileSync("docs/padroes-cadastro/revisoes/lote-001-contatores-siemens.json", "utf8"));
validarLote(m);
const catalogo = yaml.load(fs.readFileSync("docs/padroes-cadastro/catalogo-paineis-eletricos.yaml", "utf8"));
assert.equal(catalogo.regras_cadastro_assistido.revisao_rastreavel_por_familia.criterio_contatores, m.criterio);
assert.equal(catalogo.historico_decisoes.filter((d) => d.id === "D-036").length, 1);
assert.equal(catalogo.historico_decisoes.filter((d) => d.id === "D-037").length, 1);
assert.match(catalogo.regras_cadastro_assistido.exemplos_e_historico_informado.apresentacao, /antes e depois/);
const historicoGrupos = JSON.parse(fs.readFileSync("docs/padroes-cadastro/revisoes/historico-informado-grupos.json", "utf8"));
assert.equal(historicoGrupos.tenant_id, tenantId);
assert.equal(historicoGrupos.empresa_id, empresaId);
assert.equal(historicoGrupos.itens.length, 1193);
assert.equal(new Set(historicoGrupos.itens.map((i) => i.id)).size, 1193);
assert.throws(() => validarLote({ ...m, itens: [...m.itens, m.itens[0]] }));
assert.throws(() => validarLote({ ...m, itens: [{ ...m.itens[0], pendencias: ["falta bobina"] }] }));
const plano = montarPlano(m, m.itens.map((i) => i.antes), []);
assert.equal(plano.length, 18);
assert.ok(plano.every((p) => !p.aplicado && p.antes.grupo_id === p.depois.grupo_id));
assert.ok(montarPlano(m, plano.map((p) => ({ ...p.antes, ...p.depois })), []).every((p) => p.aplicado));
console.log("OK: controle por escopo/ID, não duplicação de status, invalidação técnica, pendências e idempotência do lote.");
const m2 = JSON.parse(fs.readFileSync("docs/padroes-cadastro/revisoes/lote-002-contatores-agrupados.json", "utf8"));
validarLote(m2);
assert.equal(m2.itens.length, 20);
assert.equal(m2.pendentes.length, 0);
assert.ok(m2.itens.every((i) => i.antes.grupo_id === 17 && !m.itens.some((anterior) => anterior.id === i.id)));
const plano2 = montarPlano(m2, m2.itens.map((i) => i.antes), []);
assert.ok(plano2.every((p) => !p.aplicado && p.antes.grupo_id === p.depois.grupo_id));
assert.ok(montarPlano(m2, plano2.map((p) => ({ ...p.antes, ...p.depois })), []).every((p) => p.aplicado));
for (const id of [740, 787]) assert.match(m2.itens.find((i) => i.id === id).nome, /AC-3 41A EM 400VCA/);
assert.match(m2.itens.find((i) => i.id === 758).nome, /AC-3 51A EM 400VCA/);
console.log("OK: lote 002, 20 IDs agrupados, correntes confirmadas e idempotência.");
