  assert.throws(() => planejarCinquenta(m, concorrente), /concorrente/);
  const estrangeiro = structuredClone(m); estrangeiro.empresa_id = "outra";
  assert.throws(() => validarCinquenta(estrangeiro));
  assert.throws(() => conferirCinquenta(plano[0], { ...depois[0], grupo_id: 999 }));
  assert.throws(() => conferirCinquenta(plano[0], { ...depois[0], preco: 999 }));
