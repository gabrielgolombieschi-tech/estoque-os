import fs from "node:fs";
import assert from "node:assert/strict";
import yaml from "js-yaml";
import { diretorio, impressaoTecnica, situacaoRevisao } from "./lib/controle-revisoes.mjs";
import { validarCinquenta, exigirAutorizacao, planejarCinquenta, conferirCinquenta, assinatura } from "./lib/lotes-cinquenta.mjs";
const ler = (n) => JSON.parse(fs.readFileSync(`${diretorio}/lote-${n}-cinquenta-itens.json`, "utf8"));
const m3 = ler("003"), m4 = ler("004"), m5 = ler("005");
assert.equal(assinatura(m3), "e3c564701791e73c258a4007df905f97e8199505e239a45b1d05db8751facb58");
assert.equal(assinatura(m4), "8dfcc93fa2471aa24881f22ec41574c889f3b03bd5c7b6ab9996f3f3c7af0a26");
const anteriores = fs.readdirSync(diretorio).filter((n) => /^eventos-00[12]-/.test(n)).flatMap((n) => JSON.parse(fs.readFileSync(`${diretorio}/${n}`, "utf8")));
assert.equal(new Set([...m3.itens, ...m4.itens, ...m5.itens].map((i) => i.id)).size, 150);
assert.ok([...m3.itens, ...m4.itens, ...m5.itens].every((i) => !anteriores.some((e) => e.item_id === i.id)));
assert.equal(assinatura(m5), "e34497cce0e1c0aa7aa59ba8eb97f4efe4cd5caf02fcdfbd0ab09f9d6476d66a");
exigirAutorizacao(m3);
assert.throws(() => exigirAutorizacao(m4), /aprovação humana/);
assert.throws(() => exigirAutorizacao({ ...m4, autorizacao: m3.autorizacao }), /aprovação humana/);
const aprovacao = JSON.parse(fs.readFileSync(`${diretorio}/aprovacao-004.json`, "utf8"));
exigirAutorizacao(m4, aprovacao);
assert.throws(() => exigirAutorizacao(m4, { ...aprovacao, empresa_id: "outra" }));
assert.throws(() => exigirAutorizacao(m4, { ...aprovacao, assinatura_lote: assinatura(m3) }));
assert.throws(() => exigirAutorizacao({ ...m4, data: "outra" }, aprovacao), /mudou após aprovação/);
assert.throws(() => exigirAutorizacao(m5), /aprovação humana/);
assert.throws(() => exigirAutorizacao(m5, { ...aprovacao, lote: m5.lote, assinatura_lote: assinatura(m5) }), /aprovação humana/);
for (const m of [m3, m4, m5]) {
  validarCinquenta(m);
  const atuais = m.itens.map((i) => i.antes);
  const plano = planejarCinquenta(m, atuais);
  assert.ok(plano.every((p) => !p.aplicado));
  const depois = plano.map((p) => ({ ...p.antes, ...p.depois }));
  assert.ok(planejarCinquenta(m, depois).every((p) => p.aplicado));
  for (const p of plano) conferirCinquenta(p, { ...p.antes, ...p.depois });
  const modificado = structuredClone(atuais); modificado[0].unidade_medida = "CX";
  assert.throws(() => planejarCinquenta(m, modificado), /concorrente/);
  const concorrente = structuredClone(atuais); concorrente[0].descricao = "edição humana";
  assert.throws(() => planejarCinquenta(m, concorrente), /concorrente/);
  const estrangeiro = structuredClone(m); estrangeiro.empresa_id = "outra";
  assert.throws(() => validarCinquenta(estrangeiro));
  assert.throws(() => conferirCinquenta(plano[0], { ...depois[0], grupo_id: 999 }));
  assert.throws(() => conferirCinquenta(plano[0], { ...depois[0], preco: 999 }));
  for (const i of m.itens) {
    assert.equal(situacaoRevisao(i.antes, []), "nao_revisado", "Proposta não é aprovação");
    assert.equal(i.impressao_antes, impressaoTecnica(i.antes));
  }
}
