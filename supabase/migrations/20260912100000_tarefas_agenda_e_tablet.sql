-- Reagendar: p_data nova = libera o dia antigo e reserva o novo numa operacao so
-- (se o novo dia esta ocupado, nada muda). p_data nula = vira "sem data" e
-- libera o dia. Tarefa sem data com p_data = vira agendada (precisa do dia livre).
create or replace function public.app_tarefas_reagendar(p_tarefa_id uuid, p_data date default null)
returns jsonb
language plpgsql
security definer
set search_path to 'pg_catalog', 'public'
set row_security to 'off'
as $function$
declare
  v_ctx record;
  v_tarefa public.tarefas;
  v_usuario_id uuid;
  v_detalhe text;
  v_anterior jsonb;
begin
  select * into v_ctx from public.fn_tarefas_contexto();
  v_tarefa := public.fn_tarefas_travar(p_tarefa_id, v_ctx.tenant_id, v_ctx.empresa_id);
