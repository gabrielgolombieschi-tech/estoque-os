$$;

-- Ha outra reserva ativa para este colaborador (ou para a mesma pessoa em outra
-- empresa) nesta data? Devolve o erro pronto, com os detalhes so para quem pode
-- ver a tarefa que ocupa o dia; ou nulo se o dia esta livre.
create or replace function public.fn_tarefas_conflito(
  p_tenant_id uuid,
  p_empresa_id uuid,
  p_colaborador_id uuid,
  p_usuario_id uuid,
  p_data date,
  p_excluir_tarefa_id uuid,
  p_auth_uid uuid,
  p_gestao boolean,
  p_colaborador_proprio uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path to 'pg_catalog', 'public'
set row_security to 'off'
as $function$
declare
  v_conflito record;
  v_visivel boolean;
  v_detalhe jsonb;
begin
  select r.tarefa_id,
         r.colaborador_id,
         colab.nome as colaborador_nome,
         t.tenant_id,
         t.empresa_id,
         t.colaborador_id as tarefa_colaborador_id,
         t.descricao,
         t.situacao,
         os.responsavel_aprovacao_id,
         coalesce(nullif(btrim(os.numero_os), ''), os.os_num::text, os.id::text) as numero_os,
         coalesce(nullif(btrim(os.cliente_nome), ''), 'Cliente não informado') as cliente_nome
    into v_conflito
  from public.tarefas_reservas as r
  join public.tarefas as t on t.id = r.tarefa_id
  join public.ordens_servico as os on os.id = t.os_id
  join public.colaboradores as colab on colab.id = r.colaborador_id
  where r.liberada_em is null
    and r.data = p_data
    and (r.colaborador_id = p_colaborador_id
         or (p_usuario_id is not null and r.usuario_id = p_usuario_id))
    and (p_excluir_tarefa_id is null or r.tarefa_id <> p_excluir_tarefa_id)
  order by (r.colaborador_id = p_colaborador_id) desc
  limit 1;

  if not found then
    return null;
  end if;

  v_visivel := v_conflito.tenant_id = p_tenant_id
    and v_conflito.empresa_id = p_empresa_id
    and (p_gestao
         or coalesce(v_conflito.responsavel_aprovacao_id = p_auth_uid, false)
         or (p_colaborador_proprio is not null and v_conflito.tarefa_colaborador_id = p_colaborador_proprio));

  if v_visivel then
    v_detalhe := jsonb_build_object(
      'tarefa_id', v_conflito.tarefa_id,
      'numero_os', v_conflito.numero_os,
      'cliente_nome', v_conflito.cliente_nome,
      'descricao', v_conflito.descricao,
      'situacao', v_conflito.situacao
    );
  end if;

  return public.fn_tarefas_erro(
    'colaborador_reservado',
    format('%s já está reservado(a) em %s.', v_conflito.colaborador_nome, to_char(p_data, 'DD/MM/YYYY'))
  ) || jsonb_build_object('conflito', v_detalhe, 'data', p_data, 'colaborador_id', p_colaborador_id);
end;
$function$;

-- Reserva o dia para a tarefa. Chamar dentro de um bloco com tratamento de
-- SQLSTATE 'P0T01' (dia ocupado; detail traz o erro pronto em json) e de
-- unique_violation (dois pedidos ao mesmo tempo: o indice unico decide).
create or replace function public.fn_tarefas_reservar(
  p_tarefa public.tarefas,
  p_usuario_id uuid,
  p_data date,
  p_auth_uid uuid,
  p_gestao boolean,
  p_colaborador_proprio uuid
)
returns uuid
language plpgsql
security definer
set search_path to 'pg_catalog', 'public'
set row_security to 'off'
as $function$
declare
  v_conflito jsonb;
  v_reserva_id uuid;
begin
  -- Serializa os pedidos do mesmo colaborador/dia (e da mesma pessoa/dia):
  -- o segundo espera o primeiro terminar e ja enxerga a reserva dele.
  perform pg_advisory_xact_lock(hashtextextended('tarefa-reserva:' || p_tarefa.colaborador_id::text || ':' || p_data::text, 0));
  if p_usuario_id is not null then
    perform pg_advisory_xact_lock(hashtextextended('tarefa-reserva-usuario:' || p_usuario_id::text || ':' || p_data::text, 0));
  end if;

  v_conflito := public.fn_tarefas_conflito(
    p_tarefa.tenant_id, p_tarefa.empresa_id, p_tarefa.colaborador_id, p_usuario_id, p_data,
    p_tarefa.id, p_auth_uid, p_gestao, p_colaborador_proprio
  );
  if v_conflito is not null then
    raise exception using errcode = 'P0T01', message = 'colaborador_reservado', detail = v_conflito::text;
