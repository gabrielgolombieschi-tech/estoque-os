  values (p_tarefa.tenant_id, p_tarefa.empresa_id, p_tarefa.id, p_tarefa.colaborador_id, p_usuario_id, p_data, p_auth_uid)
  returning id into v_reserva_id;

  return v_reserva_id;
end;
$function$;

