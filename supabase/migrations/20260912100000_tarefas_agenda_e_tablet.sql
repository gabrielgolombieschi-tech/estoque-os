-- Tarefas: agenda de colaborador com reserva de dia, no ERP web, no app e no
-- tablet compartilhado.
--
-- Uma tarefa amarra um colaborador a uma OS com uma descricao. Ela e "agendada"
-- (tem data e reserva o dia inteiro do colaborador) ou "sem data" (fica
-- pendente, sem reservar nada). Tarefa e apontamento sao independentes: concluir
-- uma tarefa nao gera hora nenhuma.
--
-- A regra central — um colaborador agendado num dia nao pode ser agendado de
-- novo naquele dia, por ninguem, em nenhuma outra OS — mora no banco, e nao na
-- tela: tarefas_reservas guarda uma linha por reserva, e o indice unico parcial
-- (colaborador_id, data) enquanto a reserva esta ativa e quem garante a
-- exclusividade mesmo com dois pedidos ao mesmo tempo. O mesmo vale por usuario
-- (colaboradores.user_id) para a mesma pessoa nao ser reservada por duas
-- empresas. Toda operacao que mexe na reserva (reagendar, trocar colaborador,
-- passar para sem data, cancelar, liberar) fica registrada na propria linha da
-- reserva (quem liberou, quando e por que) e no audit_log.
--
-- Concluir registra a execucao e NAO libera a reserva: o dia foi usado. Liberar
-- o dia de uma tarefa concluida e acao explicita da gestao (app_tarefas_liberar_reserva).
--
-- Quem pode o que (mesma hierarquia de fn_usuario_pode_alterar_apontamento):
--   - ADMIN, DIRETOR e COORDENACAO da empresa: criam e administram qualquer tarefa;
--   - responsavel da OS (ordens_servico.responsavel_aprovacao_id): cria e
--     administra as tarefas das OS dele;
--   - colaborador comum: ve as proprias tarefas e conclui as proprias pendentes.
-- Tudo validado no servidor, isolado por tenant e empresa. A conta do tablet
-- (APONTADOR autorizado em tablet_dispositivos) nao entra nas app_tarefas_*: ela
-- so enxerga as tarefas do colaborador identificado pelo PIN, via
-- app_tablet_tarefas / app_tablet_tarefa_concluir, e nunca aprova nem administra.
--
-- Idempotencia: criar e concluir aceitam uma chave (uuid gerada pela interface);
-- repetir a chave devolve o mesmo resultado sem gravar de novo. Concluir tambem
-- e idempotente pelo estado: concluir o que ja esta concluido devolve sucesso
-- com repetido = true.

begin;

set local lock_timeout = '5s';
set local statement_timeout = '120s';

-- Todas as funcoes do banco pertencem a postgres.
set local role postgres;

-- 1. Tabelas -------------------------------------------------------------------

create table if not exists public.tarefas (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null,
  empresa_id uuid not null,
  os_id integer not null references public.ordens_servico (id),
  colaborador_id uuid not null references public.colaboradores (id),
  tipo text not null,
  data date,
  descricao text not null,
  situacao text not null default 'pendente',
  criado_em timestamptz not null default now(),
  criado_por_user_id uuid,
  atualizado_em timestamptz not null default now(),
  atualizado_por_user_id uuid,
  concluida_em timestamptz,
  concluida_por_user_id uuid,
  concluida_por_sessao_id uuid references public.tablet_sessoes (id),
  cancelada_em timestamptz,
  cancelada_por_user_id uuid,
  cancelamento_motivo text,
  constraint chk_tarefas_tipo check (tipo in ('agendada', 'sem_data')),
  constraint chk_tarefas_situacao check (situacao in ('pendente', 'concluida', 'cancelada')),
  constraint chk_tarefas_data_por_tipo check ((tipo = 'agendada') = (data is not null)),
  constraint chk_tarefas_descricao check (char_length(btrim(descricao)) between 1 and 2000),
  constraint chk_tarefas_conclusao check ((situacao = 'concluida') = (concluida_em is not null)),
  constraint chk_tarefas_cancelamento check ((situacao = 'cancelada') = (cancelada_em is not null))
);

comment on table public.tarefas is
  'Tarefa de um colaborador numa OS. Agendada reserva o dia inteiro do colaborador (ver tarefas_reservas); sem data so fica pendente. Nao gera horas.';
comment on column public.tarefas.concluida_por_sessao_id is
  'Quando preenchido, a conclusao veio do tablet compartilhado nesta sessao de PIN (concluida_por_user_id e a conta do tablet).';

create index if not exists idx_tarefas_empresa_situacao_data
  on public.tarefas (tenant_id, empresa_id, situacao, data);
create index if not exists idx_tarefas_colaborador_data
  on public.tarefas (colaborador_id, data);
create index if not exists idx_tarefas_os
  on public.tarefas (os_id);

create table if not exists public.tarefas_reservas (
  id uuid primary key default gen_random_uuid(),
  -- Ordem de criacao dentro da tarefa: duas reservas da mesma transacao tem o
  -- mesmo criado_em, e o historico precisa saber qual veio depois.
  ordem bigint generated by default as identity,
  tenant_id uuid not null,
  empresa_id uuid not null,
  tarefa_id uuid not null references public.tarefas (id),
  colaborador_id uuid not null references public.colaboradores (id),
  usuario_id uuid,
  data date not null,
  criado_em timestamptz not null default now(),
  criado_por_user_id uuid,
  liberada_em timestamptz,
  liberada_por_user_id uuid,
  liberacao_motivo text
);

comment on table public.tarefas_reservas is
  'Reserva do dia inteiro de um colaborador por uma tarefa agendada. Uma linha por reserva; liberar preenche liberada_em (a linha fica como historico). Os indices unicos parciais garantem um colaborador (e um usuario) por dia.';

-- A exclusividade de verdade: um colaborador por dia, um usuario por dia,
-- uma reserva ativa por tarefa.
create unique index if not exists uq_tarefas_reservas__colaborador_dia
  on public.tarefas_reservas (colaborador_id, data)
  where liberada_em is null;
create unique index if not exists uq_tarefas_reservas__usuario_dia
  on public.tarefas_reservas (usuario_id, data)
  where liberada_em is null and usuario_id is not null;
create unique index if not exists uq_tarefas_reservas__tarefa_ativa
  on public.tarefas_reservas (tarefa_id)
  where liberada_em is null;
create index if not exists idx_tarefas_reservas_empresa_data
  on public.tarefas_reservas (tenant_id, empresa_id, data)
  where liberada_em is null;
create index if not exists idx_tarefas_reservas_tarefa
  on public.tarefas_reservas (tarefa_id, ordem);

create table if not exists public.tarefas_operacoes (
  chave uuid primary key,
  tenant_id uuid not null,
  operacao text not null,
  tarefa_id uuid,
  resultado jsonb not null,
  criado_em timestamptz not null default now()
);

comment on table public.tarefas_operacoes is
  'Chave de idempotencia das operacoes de tarefa (criar, concluir): repetir a chave devolve o mesmo resultado em vez de gravar de novo.';

-- Mesma postura das tabelas do tablet: RLS ligada e sem policy, entao so as
-- funcoes SECURITY DEFINER (row_security off) enxergam as tabelas.
alter table public.tarefas enable row level security;
alter table public.tarefas_reservas enable row level security;
alter table public.tarefas_operacoes enable row level security;

revoke all on table public.tarefas from public, anon, authenticated;
revoke all on table public.tarefas_reservas from public, anon, authenticated;
revoke all on table public.tarefas_operacoes from public, anon, authenticated;

grant select, insert, update, delete, truncate, references, trigger
  on public.tarefas, public.tarefas_reservas, public.tarefas_operacoes
  to service_role;

