-- Nome de quem fez: conta do ERP, perfil, colaborador vinculado ou o e-mail.
create or replace function public.fn_tarefas_nome_usuario(p_auth_uid uuid)
returns text
language sql
stable
security definer
set search_path to 'pg_catalog', 'public', 'a'
set row_security to 'off'
as $$
  select coalesce(
    (select nullif(btrim(usuario.nome), '') from a.usuario as usuario
      where usuario.auth_user_id = p_auth_uid and usuario.deleted_at is null
      order by usuario.ativo desc limit 1),
    (select nullif(btrim(perfil.nome), '') from public.profiles as perfil where perfil.id = p_auth_uid),
    (select nullif(btrim(colaborador.nome), '')::text from public.colaboradores as colaborador where colaborador.user_id = p_auth_uid limit 1),
    (select conta.email::text from auth.users as conta where conta.id = p_auth_uid)
  )
  where p_auth_uid is not null;
$$;

-- Quem esta chamando e o que pode. Levanta quando nao ha contexto de empresa ou
-- quando a conta e um tablet (o tablet tem as funcoes dele).
create or replace function public.fn_tarefas_contexto()
returns table (
  tenant_id uuid,
  empresa_id uuid,
  auth_uid uuid,
  papel text,
  colaborador_id uuid,
  gestao boolean,
  pode_criar boolean
)
language plpgsql
stable
security definer
set search_path to 'pg_catalog', 'public', 'a'
set row_security to 'off'
as $function$
declare
  v_auth_uid uuid := auth.uid();
  v_tenant_id uuid := public.current_tenant_id();
  v_empresa_id uuid := public.current_empresa_id();
  v_papel text;
  v_colaborador_id uuid;
  v_gestao boolean;
begin
  if v_auth_uid is null
     or v_tenant_id is null
     or v_empresa_id is null
     or not public.has_active_empresa_access(v_tenant_id, v_empresa_id) then
    raise exception 'Autenticação e contexto de empresa são obrigatórios.';
  end if;

  if (public.fn_tablet_dispositivo_atual()).id is not null then
    raise exception 'A conta do tablet não acessa tarefas pelo aplicativo. Identifique-se pelo PIN.';
  end if;

  v_papel := coalesce(a.fn_current_empresa_papel(v_tenant_id, v_empresa_id), '');

  select colaborador.id
    into v_colaborador_id
  from public.colaboradores as colaborador
  where colaborador.user_id = v_auth_uid
    and colaborador.tenant_id = v_tenant_id
    and colaborador.empresa_id = v_empresa_id
    and colaborador.ativo is true
  limit 1;

  v_gestao := v_papel in ('ADMIN', 'DIRETOR', 'COORDENACAO');

  return query
  select v_tenant_id, v_empresa_id, v_auth_uid, v_papel, v_colaborador_id, v_gestao,
         v_gestao or exists (
           select 1 from public.ordens_servico as os
           where os.tenant_id = v_tenant_id
             and os.empresa_id = v_empresa_id
             and os.responsavel_aprovacao_id = v_auth_uid
         );
end;
$function$;

-- Todas as tarefas que a pessoa pode ver, ja com nomes e permissoes.
create or replace function public.fn_tarefas_linhas(p_tenant_id uuid, p_empresa_id uuid, p_auth_uid uuid, p_gestao boolean, p_colaborador_id uuid)
returns setof public.tarefa_linha
language sql
stable
security definer
set search_path to 'pg_catalog', 'public'
set row_security to 'off'
as $$
  with hoje as (select public.fn_tablet_data_hoje() as d)
  select
    t.id,
    t.tipo,
    t.data,
    t.situacao,
    t.colaborador_id,
    colab.nome::text,
    (p_colaborador_id is not null and t.colaborador_id = p_colaborador_id),
    t.os_id,
    coalesce(nullif(btrim(os.numero_os), ''), os.os_num::text, os.id::text),
    os.cliente_id,
    coalesce(nullif(btrim(os.cliente_nome), ''), nullif(btrim(cli.nome), ''), 'Cliente não informado')::text,
    os.descricao_servico,
    coalesce(nullif(lower(os.status_fluxo), ''), public.mapear_status_legado_para_fluxo(os.status)),
    coalesce(os.usa_relatorio_hh, false),
    public.fn_tarefas_nome_usuario(os.responsavel_aprovacao_id),
    t.descricao,
    t.criado_em,
    public.fn_tarefas_nome_usuario(t.criado_por_user_id),
    t.atualizado_em,
    t.concluida_em,
    case when t.concluida_por_sessao_id is not null then colab.nome::text || ' (pelo tablet)'
         else public.fn_tarefas_nome_usuario(t.concluida_por_user_id) end,
    t.concluida_por_sessao_id is not null,
    t.cancelada_em,
    public.fn_tarefas_nome_usuario(t.cancelada_por_user_id),
    t.cancelamento_motivo,
    reserva.id is not null,
    ultima.liberada_em,
    public.fn_tarefas_nome_usuario(ultima.liberada_por_user_id),
    ultima.liberacao_motivo,
    (t.situacao = 'pendente' and t.data is not null and t.data < hoje.d),
    (t.data is not null and t.data = hoje.d),
    (p_gestao or coalesce(os.responsavel_aprovacao_id = p_auth_uid, false)),
    (t.situacao = 'pendente' and (p_gestao or coalesce(os.responsavel_aprovacao_id = p_auth_uid, false)
       or (p_colaborador_id is not null and t.colaborador_id = p_colaborador_id)))
  from public.tarefas as t
  cross join hoje
  join public.ordens_servico as os on os.id = t.os_id
  join public.colaboradores as colab on colab.id = t.colaborador_id
  left join public.clientes as cli
    on cli.id = os.cliente_id and cli.tenant_id = t.tenant_id and cli.empresa_id = t.empresa_id
  left join public.tarefas_reservas as reserva
    on reserva.tarefa_id = t.id and reserva.liberada_em is null
  left join lateral (
    select r.liberada_em, r.liberada_por_user_id, r.liberacao_motivo
    from public.tarefas_reservas as r
    where r.tarefa_id = t.id and r.liberada_em is not null
    order by r.liberada_em desc, r.ordem desc
    limit 1
  ) as ultima on true
  where t.tenant_id = p_tenant_id
    and t.empresa_id = p_empresa_id
    and (p_gestao
         or coalesce(os.responsavel_aprovacao_id = p_auth_uid, false)
         or (p_colaborador_id is not null and t.colaborador_id = p_colaborador_id));
$$;

create or replace function public.fn_tarefas_linha_json(p_tarefa_id uuid, p_tenant_id uuid, p_empresa_id uuid, p_auth_uid uuid, p_gestao boolean, p_colaborador_id uuid)
returns jsonb
language sql
stable
security definer
set search_path to 'pg_catalog', 'public'
set row_security to 'off'
as $$
  select to_jsonb(linha)
  from public.fn_tarefas_linhas(p_tenant_id, p_empresa_id, p_auth_uid, p_gestao, p_colaborador_id) as linha
