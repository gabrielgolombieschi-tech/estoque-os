      numero_os text,
      cliente_id integer,
      cliente_nome text,
      os_descricao text,
      os_status_fluxo text,
      -- Para a tela abrir a OS do jeito certo: a de HH lanca por horarios.
      os_usa_relatorio_hh boolean,
      os_responsavel_nome text,
      descricao text,
      criado_em timestamptz,
      criado_por_nome text,
      atualizado_em timestamptz,
      concluida_em timestamptz,
      concluida_por_nome text,
      concluida_pelo_tablet boolean,
      cancelada_em timestamptz,
      cancelada_por_nome text,
      cancelamento_motivo text,
      reserva_ativa boolean,
      reserva_liberada_em timestamptz,
      reserva_liberada_por_nome text,
      reserva_liberacao_motivo text,
      atrasada boolean,
      hoje boolean,
      pode_gerir boolean,
      pode_concluir boolean
    );
  end if;

  -- O tipo pode ter nascido numa versao anterior desta migration, sem os dois
  -- campos da OS. Sem isto, reaplicar o arquivo deixaria fn_tarefas_linhas com
  -- mais colunas do que o tipo tem.
  if not exists (
    select 1
    from pg_type t
    join pg_namespace n on n.oid = t.typnamespace
    join pg_attribute a on a.attrelid = t.typrelid
    where n.nspname = 'public'
      and t.typname = 'tarefa_linha'
      and a.attname = 'os_usa_relatorio_hh'
      and not a.attisdropped
  ) then
    alter type public.tarefa_linha add attribute os_usa_relatorio_hh boolean cascade;
    alter type public.tarefa_linha add attribute os_responsavel_nome text cascade;
  end if;
end;
$tipo$;

