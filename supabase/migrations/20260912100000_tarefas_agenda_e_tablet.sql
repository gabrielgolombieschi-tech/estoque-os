declare
  v_acl text;
  v_nome text;
begin
  foreach v_nome in array array['tarefas', 'tarefas_reservas', 'tarefas_operacoes'] loop
    if not exists (select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relname = v_nome and c.relrowsecurity) then
      raise exception 'rls_desligada: %', v_nome;
    end if;
    if exists (select 1 from pg_policies where schemaname = 'public' and tablename = v_nome) then
      raise exception 'policy_inesperada: %', v_nome;
    end if;
    if has_table_privilege('authenticated', format('public.%I', v_nome), 'select') then
      raise exception 'tabela_aberta_para_authenticated: %', v_nome;
    end if;
  end loop;

  foreach v_nome in array array['uq_tarefas_reservas__colaborador_dia', 'uq_tarefas_reservas__usuario_dia', 'uq_tarefas_reservas__tarefa_ativa'] loop
    if not exists (select 1 from pg_indexes where schemaname = 'public' and indexname = v_nome and indexdef ilike 'create unique index%') then
      raise exception 'indice_unico_ausente: %', v_nome;
    end if;
  end loop;

  if not exists (select 1 from pg_trigger where tgname = 'trg_tarefas_audit' and tgrelid = 'public.tarefas'::regclass)
     or not exists (select 1 from pg_trigger where tgname = 'trg_tarefas_reservas_audit' and tgrelid = 'public.tarefas_reservas'::regclass) then
    raise exception 'auditoria_ausente';
  end if;

  for v_acl in
    select coalesce(p.proacl::text, '')
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and (p.proname like 'app\_tarefas\_%' or p.proname like 'fn\_tarefas\_%' or p.proname like 'app\_tablet\_tarefa%')
  loop
    if v_acl like '%anon=%' or v_acl like '{=X%' then
      raise exception 'grant_tarefas_aberto: %', v_acl;
    end if;
  end loop;

  for v_acl in
    select p.proname::text
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and p.proname like 'fn\_tarefas\_%'
      and has_function_privilege('authenticated', p.oid, 'execute')
  loop
    raise exception 'helper_exposto: %', v_acl;
  end loop;
end;
