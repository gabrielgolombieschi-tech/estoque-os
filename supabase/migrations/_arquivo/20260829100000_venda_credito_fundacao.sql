create or replace view r.r_clientes_documento_pendencia
with (security_invoker = true)
as
select
  c.tenant_id,
  c.empresa_id,
  c.id as cliente_id,
  c.nome as cliente_nome,
  c.documento,
  c.documento_norm,
  c.ativo,
  case
    when nullif(c.documento_norm, '') is null then 'SEM_DOCUMENTO'
    when length(c.documento_norm) = 14 and not public.cnpj_valido(c.documento_norm) then 'CNPJ_INVALIDO'
    else null
  end as pendencia
from public.clientes c
where c.ativo = true
  and (
    nullif(c.documento_norm, '') is null
    or (length(c.documento_norm) = 14 and not public.cnpj_valido(c.documento_norm))
  );

grant select on r.r_clientes_documento_pendencia to authenticated;

notify pgrst, 'reload schema';

