alter table public.clientes
  add column if not exists documento_raiz text
  generated always as (
    case
      when length(public.normalize_doc(documento)) = 14
        then left(public.normalize_doc(documento), 8)
      else null
    end
  ) stored;

create index if not exists idx_clientes_tenant_empresa_documento_raiz
  on public.clientes (tenant_id, empresa_id, documento_raiz)
  where documento_raiz is not null;

create or replace function public.cnpj_valido(p_documento text)
returns boolean
language plpgsql
immutable
strict
set search_path = pg_catalog
as $$
declare
  v text := regexp_replace(p_documento, '[^0-9]', '', 'g');
  v_soma integer := 0;
  v_resto integer;
  v_d1 integer;
  v_d2 integer;
  v_pesos1 integer[] := array[5,4,3,2,9,8,7,6,5,4,3,2];
  v_pesos2 integer[] := array[6,5,4,3,2,9,8,7,6,5,4,3,2];
  i integer;
begin
  if length(v) <> 14 or v ~ '^(.)\1{13}$' then
    return false;
  end if;

  for i in 1..12 loop
    v_soma := v_soma + substr(v, i, 1)::integer * v_pesos1[i];
  end loop;
  v_resto := v_soma % 11;
  v_d1 := case when v_resto < 2 then 0 else 11 - v_resto end;

  v_soma := 0;
  for i in 1..13 loop
    v_soma := v_soma + substr(v, i, 1)::integer * v_pesos2[i];
  end loop;
  v_resto := v_soma % 11;
  v_d2 := case when v_resto < 2 then 0 else 11 - v_resto end;

  return v_d1 = substr(v, 13, 1)::integer
     and v_d2 = substr(v, 14, 1)::integer;
end;
$$;

revoke all on function public.cnpj_valido(text) from public, anon;
grant execute on function public.cnpj_valido(text) to authenticated, service_role;

create table if not exists public.cliente_unidades (
  id bigint generated by default as identity primary key,
  tenant_id uuid not null,
  empresa_id uuid not null default public.current_empresa_id(),
  cliente_id integer not null,
  nome text not null,
  codigo text,
  documento varchar(20),
  cidade varchar(120),
  uf varchar(2),
  contato_nome text,
  contato_email text,
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid default a.fn_current_usuario_id(),
  updated_by uuid,
  constraint cliente_unidades_nome_nao_vazio_ck check (btrim(nome) <> ''),
  constraint cliente_unidades_uf_ck check (uf is null or uf ~ '^[A-Z]{2}$'),
  constraint cliente_unidades_cliente_fk
    foreign key (tenant_id, empresa_id, cliente_id)
    references public.clientes (tenant_id, empresa_id, id)
    on delete cascade
);

create unique index if not exists cliente_unidades_tenant_empresa_id_ux
  on public.cliente_unidades (tenant_id, empresa_id, id);

create unique index if not exists cliente_unidades_nome_ux
  on public.cliente_unidades (tenant_id, empresa_id, cliente_id, upper(btrim(nome)));

create index if not exists cliente_unidades_cliente_idx
  on public.cliente_unidades (tenant_id, empresa_id, cliente_id, ativo);

alter table public.cliente_unidades enable row level security;

drop policy if exists cliente_unidades_select on public.cliente_unidades;
create policy cliente_unidades_select
on public.cliente_unidades for select to authenticated
using (
  tenant_id = public.current_tenant_id()
  and empresa_id = public.current_empresa_id()
  and public.has_active_empresa_access(tenant_id, empresa_id)
);

drop policy if exists cliente_unidades_write on public.cliente_unidades;
create policy cliente_unidades_write
on public.cliente_unidades for all to authenticated
using (
  tenant_id = public.current_tenant_id()
  and empresa_id = public.current_empresa_id()
  and public.has_active_empresa_access(tenant_id, empresa_id)
  and (
    public.can('cad_clientes', 'write')
    or a.fn_current_empresa_papel(tenant_id, empresa_id) in ('ADMIN','DIRETOR','COORDENACAO','FINANCEIRO')
  )
)
with check (
  tenant_id = public.current_tenant_id()
  and empresa_id = public.current_empresa_id()
  and public.has_active_empresa_access(tenant_id, empresa_id)
  and (
    public.can('cad_clientes', 'write')
    or a.fn_current_empresa_papel(tenant_id, empresa_id) in ('ADMIN','DIRETOR','COORDENACAO','FINANCEIRO')
  )
);

grant select, insert, update, delete on public.cliente_unidades to authenticated;
grant all on public.cliente_unidades to service_role;
grant usage, select on sequence public.cliente_unidades_id_seq to authenticated, service_role;

alter table public.ordens_servico
